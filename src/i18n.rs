    /// Matches a system locale onto a menu entry; unknown languages read as English.
    pub fn from_locale(locale: &str) -> Lang {
        let locale = locale.to_ascii_lowercase();
        let mut parts = locale.split(['-', '_', '.', '@']);
        let language = parts.next().unwrap_or("");
        // The region is the first two-letter (or `419`) subtag; scripts and encodings are longer.
        let region = parts.find(|part| {
            *part == "419" || (part.len() == 2 && part.chars().all(|c| c.is_ascii_alphabetic()))
        });
        match language {
            "en" => Lang::EnUs,
            "zh" => Lang::ZhCn,
            "es" => {
                if region.is_some_and(|region| LATIN_AMERICA.contains(&region)) {
                    Lang::Es419
                } else {
                    Lang::EsEs
                }
            }
            "hi" => Lang::HiIn,
            "ar" => Lang::Ar,
            "pt" => {
                if region == Some("br") {
                    Lang::PtBr
                } else {
                    Lang::PtPt
                }
            }
            "ja" => Lang::JaJp,
            "ru" => Lang::RuRu,
            "fr" => Lang::FrFr,
            "de" => Lang::DeDe,
            // `in` is the legacy ISO code for Indonesian.
            "id" | "in" => Lang::Id,
            "it" => Lang::ItIt,
            "ko" => Lang::Ko,
            "th" => Lang::Th,
            "tr" => Lang::Tr,
            "fa" => Lang::Fa,
            "nl" => Lang::Nl,
            "pl" => Lang::Pl,
            "vi" => Lang::Vi,
            "cs" => Lang::Cs,
            "el" => Lang::El,
            "sv" => Lang::Sv,
            "uk" => Lang::Uk,
            "hu" => Lang::Hu,
            "ro" => Lang::Ro,
            "da" => Lang::Da,
            "fi" => Lang::Fi,
            // Bokmål, Nynorsk and the macrolanguage code all read as Norwegian.
            "no" | "nb" | "nn" => Lang::No,
            "sk" => Lang::Sk,
            "bg" => Lang::Bg,
            "hr" => Lang::Hr,
            "lt" => Lang::Lt,
            "sr" => Lang::Sr,
            "lv" => Lang::Lv,
            "sl" => Lang::Sl,
            "et" => Lang::Et,
            // `iw` is the legacy ISO code for Hebrew.
            "he" | "iw" => Lang::He,
            "ms" => Lang::Ms,
            // `tl` (Tagalog) is what most systems report for Filipino.
            "fil" | "tl" => Lang::Fil,
            _ => Lang::EnUs,
        }
    }

    /// The OS UI language; English when the OS reports nothing.
    pub fn system() -> Lang {
        sys_locale::get_locale()
            .as_deref()
            .map(Lang::from_locale)
            .unwrap_or(Lang::EnUs)
    }

